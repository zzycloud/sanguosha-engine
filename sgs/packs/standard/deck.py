@register_deck("standard")
def standard_deck():
    cards = []
    for suit, items in _STANDARD.items():
        for rank, name in items:
            cards.append((name, suit, rank))
    for suit, rank, name in _EX:
        cards.append((name, suit, rank))
    return cards


@register_deck("standard_no_ex")
def standard_no_ex_deck():
    return [(n, s, r) for suit, items in _STANDARD.items() for r, n in items for s in [suit]]
